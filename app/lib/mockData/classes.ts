// Helper functions
export const getEnrolledClasses = (): FitnessClass[] => {
  return mockClasses.filter(c => c.userStatus === 'enrolled');
};

export const getAvailableClasses = (): FitnessClass[] => {
  return mockClasses.filter(c => c.userStatus !== 'enrolled');
};

export const getClassById = (id: string): FitnessClass | undefined => {
  return mockClasses.find(c => c.id === id);
};
